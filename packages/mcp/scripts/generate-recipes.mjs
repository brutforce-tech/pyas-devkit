/**
 * The recipes' files (recipes/<runtime>/...) as one generated module, so the published package
 * carries them in both builds without reading files at run time:
 *
 *   npm run generate:recipes
 *
 * The end-to-end suite runs the files in recipes/ themselves against the API.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const recipes = join(root, 'recipes')

const walk = (dir) => readdirSync(dir).sort().flatMap((name) => {
    const path = join(dir, name)
    return statSync(path).isDirectory() ? walk(path) : [path]
})

export const renderRecipeFiles = () => {
    // tsconfig.json typechecks the recipes here; it is not part of any recipe.
    const files = Object.fromEntries(walk(recipes).filter((path) => !path.endsWith('tsconfig.json')).map((path) => [relative(recipes, path).split('\\').join('/'), readFileSync(path, 'utf8').replace(/\r\n/g, '\n')]))
    return [
        '// Generated by scripts/generate-recipes.mjs from recipes/. Do not edit: change the files there and run npm run generate:recipes.',
        `export const RECIPE_FILES: Record<string, string> = ${JSON.stringify(files, null, 4)}`,
        '',
    ].join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
    writeFileSync(join(root, 'src', 'recipeFiles.ts'), renderRecipeFiles())
    console.log('src/recipeFiles.ts written')
}

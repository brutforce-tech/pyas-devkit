/**
 * Generates the SDK's types and its table of operations from the committed
 * snapshot of the API's OpenAPI document (openapi/v2.json):
 *
 *   src/generated/schema.ts       every request and response type (openapi-typescript)
 *   src/generated/operations.ts   each operation's method, path and parameters, and the
 *                                 typed resource tree (`pyas.events.list(...)`), with each
 *                                 operation's summary as its documentation
 *
 * The client (src/client.ts) is written by hand; this file only describes the API.
 *
 *   npm run openapi:pull && npm run generate
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const doc = JSON.parse(readFileSync(join(root, 'openapi', 'v2.json'), 'utf8'))
const HEADER = '// Generated by scripts/generate.mjs from openapi/v2.json. Do not edit: regenerate.\n'

/**
 * PyasConnect's own endpoints (the session token in the body) and the redirect page: only PyasConnect and
 * a browser use them. Servers connect accounts with connect.oauth and connect.accounts.create instead.
 */
const BROWSER_ONLY = new Set(['connect.info', 'connect.authorize', 'connect.complete', 'connect.go'])

const comment = (text, indent) => {
    const lines = String(text).replace(/\*\//g, '*\\/').split('\n')
    return `${indent}/**\n${lines.map((l) => `${indent} *${l ? ` ${l}` : ''}`).join('\n')}\n${indent} */\n`
}

const resolve = (schema) => (schema?.$ref ? doc.components.schemas[schema.$ref.split('/').pop()] : schema)

const operations = []
for (const [path, item] of Object.entries(doc.paths)) {
    for (const [method, op] of Object.entries(item)) {
        if (!op?.operationId || BROWSER_ONLY.has(op.operationId)) continue
        const params = op.parameters ?? []
        const ok = Object.entries(op.responses ?? {}).find(([code]) => /^2/.test(code))
        const okContent = ok?.[1]?.content ?? {}
        const query = params.filter((p) => p.in === 'query')
        const bodyContent = op.requestBody?.content ?? {}
        const jsonBody = bodyContent['application/json'] ? resolve(bodyContent['application/json'].schema) : null
        const result = okContent['application/json']
            ? (query.some((p) => p.name === 'cursor') ? 'paged' : 'json')
            : okContent['text/event-stream'] ? 'stream'
            : Object.keys(okContent).length ? 'binary' : 'empty'
        operations.push({
            id: op.operationId,
            method: method.toUpperCase(),
            path,
            pathParams: params.filter((p) => p.in === 'path').map((p) => p.name),
            query: query.map((p) => p.name),
            requiredQuery: query.filter((p) => p.required).map((p) => p.name),
            // "Comma-separated" parameters take a string or an array (joined with commas).
            lists: query.filter((p) => /comma-separated/i.test(p.description ?? '')).map((p) => p.name),
            idempotent: params.some((p) => p.in === 'header' && p.name === 'Idempotency-Key'),
            ifMatch: params.some((p) => p.in === 'header' && p.name === 'If-Match'),
            body: jsonBody ? 'json' : Object.keys(bodyContent).length ? 'binary' : null,
            bodyRequired: !!op.requestBody?.required && (jsonBody?.required?.length ?? 0) > 0,
            bodyKeys: jsonBody?.properties ? Object.keys(jsonBody.properties) : [],
            result,
            summary: op.summary ?? '',
            description: op.description ?? '',
            deprecated: !!op.deprecated,
        })
    }
}
operations.sort((a, b) => a.id.localeCompare(b.id))

// A parameter in two places (path, query, body) would be ambiguous in one params object. The API
// takes the account and calendar of a write in either the query or the body: the SDK sends them
// in the query. Any other name in two places is shaped by hand.
const EITHER_QUERY_OR_BODY = new Set(['accountId', 'calendarRef'])
for (const o of operations) {
    o.bodyKeys = o.bodyKeys.filter((k) => !(EITHER_QUERY_OR_BODY.has(k) && o.query.includes(k)))
    const seen = new Map()
    for (const [where, names] of [['path', o.pathParams], ['query', o.query], ['body', o.bodyKeys]]) {
        for (const n of names) {
            if (seen.has(n)) throw new Error(`${o.id}: "${n}" is both a ${seen.get(n)} and a ${where} parameter; shape this operation by hand`)
            seen.set(n, where)
        }
    }
}

// The resource tree, from the dotted ids; a name cannot be both a method and a namespace.
const tree = {}
for (const o of operations) {
    const parts = o.id.split('.')
    let node = tree
    for (const part of parts.slice(0, -1)) {
        if (node[part]?.op) throw new Error(`${o.id}: "${part}" is already a method`)
        node = node[part] ??= {}
    }
    const leaf = parts[parts.length - 1]
    if (node[leaf] && !node[leaf].op) throw new Error(`${o.id}: "${leaf}" is already a namespace`)
    node[leaf] = { op: o }
}

const signature = (o) => {
    const id = `'${o.id}'`
    const optional = !o.pathParams.length && !o.requiredQuery.length && !o.bodyRequired
    const params = `params${optional ? '?' : ''}: Params<${id}>`
    const options = 'options?: RequestOptions'
    switch (o.result) {
        case 'paged': return `(${params}, ${options}): PagePromise<Item<${id}>>`
        case 'binary': return `(${params}, ${options}): Promise<BinaryResult>`
        case 'stream': return `(${params}, ${options}): ServerSentEventStream`
        case 'empty': return `(${params}, ${options}): Promise<void>`
        default: return o.body === 'binary'
            ? `(${params}, file: BinaryInput, ${options}): Promise<Data<${id}>>`
            : `(${params}, ${options}): Promise<Data<${id}>>`
    }
}

const docOf = (o) => {
    const first = o.description.split(/\n\s*\n/)[0]?.trim()
    const lines = [o.summary, first && first !== o.summary ? `\n${first}` : '', `\n\`${o.method} ${o.path}\` (\`${o.id}\`)`]
    if (o.idempotent) lines.push('\nSafe to retry: the SDK sends an idempotency key (pass your own as `options.idempotencyKey`).')
    if (o.ifMatch) lines.push('\nPass `options.ifMatch` (the event\'s `version`) to change it only if nobody else has.')
    if (o.result === 'paged') lines.push('\nOne page with `await`; every page with `for await (const item of ...)`.')
    if (o.deprecated) lines.push('\n@deprecated')
    return lines.filter(Boolean).join('\n')
}

const emitTree = (node, indent) => Object.entries(node).map(([name, child]) => child.op
    ? `${comment(docOf(child.op), indent)}${indent}${name}${signature(child.op)}`
    : `${indent}${name}: {\n${emitTree(child, `${indent}    `)}\n${indent}}`).join('\n')

const table = operations.map((o) => `    '${o.id}': ${JSON.stringify({
    method: o.method, path: o.path, pathParams: o.pathParams, query: o.query, lists: o.lists,
    idempotent: o.idempotent, ifMatch: o.ifMatch, body: o.body, result: o.result,
})},`).join('\n')

const listParams = operations.filter((o) => o.lists.length).map((o) => `    '${o.id}': ${o.lists.map((l) => `'${l}'`).join(' | ')}`).join('\n')

const operationsTs = `${HEADER}
import type { BinaryInput, BinaryResult, Data, Item, PagePromise, Params, RequestOptions, ServerSentEventStream } from '../types'

export type OperationResult = 'json' | 'paged' | 'binary' | 'stream' | 'empty'

export interface OperationSpec {
    method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE'
    path: string
    pathParams: readonly string[]
    query: readonly string[]
    lists: readonly string[]
    idempotent: boolean
    ifMatch: boolean
    body: 'json' | 'binary' | null
    result: OperationResult
}

/** Every operation the SDK calls, by its operation id (the API's \`operationId\`). */
export const OPERATIONS = {
${table}
} as const satisfies Record<string, OperationSpec>

export type OperationId = keyof typeof OPERATIONS

/** Query parameters that take a list: a string, or an array the SDK joins with commas. */
export interface ListParams {
${listParams}
}

/** The API as resources: \`pyas.events.list(...)\`, \`pyas.webhooks.deliveries.replay(...)\`. */
export interface Resources {
${emitTree(tree, '    ')}
}
`

const ast = await openapiTS(doc, { exportType: true, alphabetize: true })
writeFileSync(join(root, 'src', 'generated', 'schema.ts'), `${HEADER}/* eslint-disable */\n${astToString(ast)}`)
writeFileSync(join(root, 'src', 'generated', 'operations.ts'), operationsTs)
console.log(`${operations.length} operations (${BROWSER_ONLY.size} browser-only left to PyasConnect), ${Object.keys(doc.components.schemas).length} schemas`)
